"use client";

import { useState } from "react";
import Link from "next/link";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { toast } from "sonner";
import { Check, Copy } from "lucide-react";

import { useAuth } from "@/lib/auth-context";
import { ApiError, auth as authApi, isOwnScopeRole, type Permissions, type Role } from "@/lib/api-client";
import { accessBaseline, assignableRoles, deviates, payloadFor, ROLE_NAMES } from "@/lib/settings";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Field } from "@/components/taggify/field";
import { AccessEditor } from "@/components/settings/access-editor";

const errText = (e: unknown, fallback: string) => (e instanceof ApiError || e instanceof Error ? e.message : fallback);
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
/** Order in the picker: the accounts added here most often first. Creators are added with a page, from Creators. */
const ORDER: Role[] = ["TEAM_MEMBER", "PLAN_MAKER", "FINANCE", "ADMIN", "CREATOR"];

const HINT: Record<Role, string> = {
  TEAM_MEMBER: "Works on a creator's pages: submits posts and proofs.",
  PLAN_MAKER: "Builds plans for clients and follows their campaigns.",
  FINANCE: "Approves invoices, pays vendors and tracks receivables.",
  ADMIN: "Runs everything. Untick sections to make a restricted admin.",
  CREATOR: "Owns pages and gets paid for posts.",
};

/**
 * POST /auth/signup: email is the login, the password is generated by the server
 * and shown once. Who may create what is the server's rule (users.edit; an admin
 * only by a full admin; access never more than the creator's own).
 */
export function AddPersonDialog({ open, onClose }: { open: boolean; onClose: () => void }) {
  const { user, accessToken } = useAuth();
  const qc = useQueryClient();
  const [email, setEmail] = useState("");
  const [name, setName] = useState("");
  const [phone, setPhone] = useState("");
  const [role, setRole] = useState<Role | "">("");
  const [access, setAccess] = useState<Permissions | null>(null);
  const [touched, setTouched] = useState(false);
  const [copied, setCopied] = useState(false);

  const phoneDigits = phone.replace(/\D/g, "");
  const emailError = !EMAIL.test(email.trim()) ? "Enter an email like name@gmail.com. It's how they sign in." : null;
  const phoneError = phoneDigits.length > 0 && phoneDigits.length !== 10 ? "Enter a 10-digit mobile number, or leave it empty." : null;
  const creator = role === "CREATOR";

  const create = useMutation({
    mutationFn: () =>
      authApi.signup(accessToken!, {
        email: email.trim(),
        name: name.trim() || undefined,
        phoneNumber: phoneDigits ? `+91${phoneDigits}` : undefined,
        role: role as Role,
        // Staff roles: always sent, so the server clamps it to the creator's own access
        // (signup only clamps when access is sent). Own-scope roles: only when something is off.
        permissions: access && (!isOwnScopeRole(role as Role) || deviates(role as Role, access)) ? payloadFor(role as Role, access) : undefined,
      }),
    onSuccess: () => qc.invalidateQueries({ queryKey: ["adminUsers"] }),
  });
  const made = create.data;

  function close() {
    setEmail("");
    setName("");
    setPhone("");
    setRole("");
    setAccess(null);
    setTouched(false);
    setCopied(false);
    create.reset();
    onClose();
  }

  return (
    <Dialog open={open} onOpenChange={(o) => !o && !made && close()}>
      {/* Once the password is showing, only Done closes: a stray click must not lose it. */}
      <DialogContent className="max-h-[90dvh] overflow-y-auto sm:max-w-xl" hideClose={!!made} onInteractOutside={(e) => made && e.preventDefault()} onEscapeKeyDown={(e) => made && e.preventDefault()}>
        {made ? (
          <>
            <DialogHeader>
              <DialogTitle>{made.user.name?.trim() || made.user.email} can sign in</DialogTitle>
              <DialogDescription>Share this login with them now. The password won&apos;t be shown again. They sign in with the email and confirm a code we send to it.</DialogDescription>
            </DialogHeader>
            <div className="flex flex-col gap-2 rounded-card border p-4">
              <p className="text-small text-muted-foreground">
                {ROLE_NAMES[made.user.role]} · {made.user.email}
              </p>
              <div className="flex items-center gap-2">
                <code className="min-w-0 flex-1 break-all rounded-md border bg-muted px-3 py-2 font-mono text-body-strong" data-testid="generated-password">
                  {made.generatedPassword}
                </code>
                <Button
                  variant="outline"
                  onClick={async () => {
                    try {
                      await navigator.clipboard.writeText(`Email: ${made.user.email}\nPassword: ${made.generatedPassword}`);
                      setCopied(true);
                    } catch {
                      toast.error("Couldn't copy. Select the password and copy it by hand.");
                    }
                  }}
                >
                  {copied ? <Check /> : <Copy />}
                  {copied ? "Copied" : "Copy login"}
                </Button>
              </div>
            </div>
            <DialogFooter>
              <Button onClick={close}>Done</Button>
            </DialogFooter>
          </>
        ) : (
          <form
            className="flex flex-col gap-5"
            onSubmit={(e) => {
              e.preventDefault();
              setTouched(true);
              if (!emailError && !phoneError && role && !creator) create.mutate();
            }}
          >
            <DialogHeader>
              <DialogTitle>Add person</DialogTitle>
              <DialogDescription>They get a login straight away. We make the password; you share it with them.</DialogDescription>
            </DialogHeader>

            <div className="grid gap-4 sm:grid-cols-2">
              <Field label="Email" className="sm:col-span-2" error={touched ? emailError : null}>
                {(a) => <Input {...a} type="email" autoComplete="off" value={email} onChange={(e) => setEmail(e.target.value)} onBlur={() => setTouched(true)} placeholder="name@gmail.com" maxLength={254} />}
              </Field>
              <Field label="Name (optional)">{(a) => <Input {...a} value={name} onChange={(e) => setName(e.target.value)} placeholder="Their name" maxLength={100} />}</Field>
              <Field label="Mobile (optional)" error={touched ? phoneError : null} description="10 digits. We add +91.">
                {(a) => <Input {...a} type="tel" inputMode="numeric" value={phone} onChange={(e) => setPhone(e.target.value.replace(/[^\d\s]/g, "").slice(0, 12))} placeholder="98765 43210" />}
              </Field>
              <Field label="Role" className="sm:col-span-2" error={touched && !role ? "Choose a role." : null} description={role ? HINT[role] : undefined}>
                {(a) => (
                  <Select
                    value={role}
                    onValueChange={(v) => {
                      setRole(v as Role);
                      setAccess(accessBaseline(v as Role));
                    }}
                  >
                    <SelectTrigger id={a.id} aria-describedby={a["aria-describedby"]} aria-invalid={a["aria-invalid"]}>
                      <SelectValue placeholder="Choose a role" />
                    </SelectTrigger>
                    <SelectContent>
                      {ORDER.filter((r) => assignableRoles(user).includes(r)).map((r) => (
                        <SelectItem key={r} value={r}>
                          {ROLE_NAMES[r]}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                )}
              </Field>
            </div>

            {creator ? (
              <p className="rounded-md bg-muted px-3 py-2 text-small text-fg-strong">
                A creator is added with their first page, so their login and page arrive together.{" "}
                <Link href="/creators" className="font-semibold text-link hover:text-link-hover">
                  Go to Inventory → Add page
                </Link>
              </p>
            ) : (
              role &&
              access && (
                <section aria-labelledby="new-access" className="flex flex-col gap-2">
                  <h3 id="new-access" className="text-card-title">
                    {isOwnScopeRole(role) ? "Access (their own content only)" : role === "ADMIN" ? "Access (untick to restrict)" : "Access"}
                  </h3>
                  {!isOwnScopeRole(role) && role !== "ADMIN" && <p className="text-small text-muted-foreground">Starts at a plain {ROLE_NAMES[role]}&apos;s access. Tick more to give extra. You can only give access you have yourself.</p>}
                  <AccessEditor value={access} onChange={setAccess} role={role} disabled={create.isPending} />
                </section>
              )
            )}

            {create.isError && (
              <p role="alert" className="text-small text-danger-helper">
                {errText(create.error, "Couldn't add this person.")}
              </p>
            )}
            <DialogFooter>
              <Button type="button" variant="ghost" onClick={close}>
                Cancel
              </Button>
              <Button type="submit" disabled={create.isPending || creator}>
                {create.isPending ? "Adding…" : "Add person"}
              </Button>
            </DialogFooter>
          </form>
        )}
      </DialogContent>
    </Dialog>
  );
}
