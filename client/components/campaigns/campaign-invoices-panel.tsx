"use client";

import Link from "next/link";
import { useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";

import { Button } from "@/components/ui/button";
import { Panel } from "@/components/ui/panel";
import { StatusPill } from "@/components/ui/status-pill";
import { TableSkeleton, EmptyState, ErrorNotice } from "@/components/ui/table-parts";
import { DownloadIcon } from "@/components/icons";
import { invoices as invoicesApi, ApiError, hasAccess, type Campaign, type Invoice, type Permissions, type Role } from "@/lib/api-client";
import { money, personLabel } from "@/lib/format";
import { InvoiceAttachmentControl } from "@/components/invoices/invoice-attachment";
import { PaySheet, toPaymentInvoice } from "@/components/payments/pay-sheet";

/**
 * Campaign page → "Invoices": the campaign's invoices (server-scoped: a
 * creator only sees their own). Creators raise their own invoices from
 * the Invoices page (user request, 13 Sep — "invoice will be generated by
 * creator's only"); Admin / Finance approve and mark paid from here
 * (Finance approves too since 23 Sep). finance.manage (15 Sep) opens the
 * same actions to a granted non-admin role — see invoices/page.tsx's
 * canManage/canApprove for the matching gate.
 */
export function CampaignInvoicesPanel({
  token,
  campaign,
  role,
  permissions,
}: {
  token: string;
  campaign: Campaign;
  role: Role | undefined;
  permissions: Permissions | undefined;
}) {
  const user = { role, permissions };
  const isAdmin = hasAccess(user, "finance.approve");
  const canMarkPaid = hasAccess(user, "finance.pay");
  const isCreator = role === "CREATOR";

  const invoicesQuery = useQuery({
    queryKey: ["invoices", { campaignId: campaign.id }],
    queryFn: () => invoicesApi.list(token, { campaignId: campaign.id, pageSize: 100 }),
  });
  const campaignInvoices = invoicesQuery.data?.items ?? [];

  return (
    <div className="flex flex-col gap-4">
      <Panel
        title="Invoices"
        subtitle={
          campaignInvoices.length === 0
            ? "Nothing invoiced for this campaign yet."
            : isCreator
              ? `${campaignInvoices.length} invoice${campaignInvoices.length === 1 ? "" : "s"} for your work on this campaign.`
              : `${campaignInvoices.length} raised for this campaign so far.`
        }
        action={
          <Link href="/invoices" className="text-[0.8125rem] font-semibold text-blue hover:text-text">
            {isCreator ? "Raise invoice" : "Open Invoices"}
          </Link>
        }
      >
        {invoicesQuery.isLoading ? (
          <TableSkeleton />
        ) : campaignInvoices.length === 0 ? (
          <EmptyState label={isCreator ? "Raise an invoice for your posts from the Invoices page." : "No invoices for this campaign yet."} />
        ) : (
          <div className="flex flex-col gap-2" data-testid="campaign-invoice-list">
            {campaignInvoices.map((inv) => (
              <CampaignInvoiceRow key={inv.id} token={token} inv={inv} isAdmin={isAdmin} canMarkPaid={canMarkPaid} />
            ))}
          </div>
        )}
      </Panel>
    </div>
  );
}

// ── Existing invoices on this campaign ───────────────────────────────

function CampaignInvoiceRow({ token, inv, isAdmin, canMarkPaid }: { token: string; inv: Invoice; isAdmin: boolean; canMarkPaid: boolean }) {
  const queryClient = useQueryClient();
  const refresh = () => queryClient.invalidateQueries({ queryKey: ["invoices"] });
  const approveMutation = useMutation({ mutationFn: () => invoicesApi.approve(token, inv.id), onSuccess: refresh });
  const downloadMutation = useMutation({ mutationFn: () => invoicesApi.downloadPdf(token, inv.id, inv.invoiceNumber) });
  // Paying opens the same TDS + mandatory-receipt PaySheet the Payments tab
  // uses (28 Sep) — an invoice is paid off exclusively through a Payout now.
  const [paying, setPaying] = useState(false);
  // Posts beyond their campaign booking on it (29 Sep): Approve and Pay are off until it's rejected and re-raised.
  const overQuota = inv.overQuotaCount ?? 0;
  // Payment only once approved (the Payout flow's own eligibility check enforces the same).
  const payable = inv.status === "APPROVED" && overQuota === 0;
  const raisedByCreator = !inv.raisedBy || inv.raisedBy.id === inv.creatorId;
  const error = [approveMutation, downloadMutation].find((m) => m.isError)?.error;

  return (
    <div data-testid={`campaign-invoice-${inv.id}`} className="flex flex-col gap-2 rounded-md border border-border px-4 py-3">
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5">
        <div className="min-w-0 flex-1">
          <p className="flex flex-wrap items-center gap-2">
            <span className="font-mono text-[0.75rem] text-text-faint">{inv.invoiceNumber}</span>
            <span className="truncate text-[0.875rem] font-semibold">{personLabel(inv.creator, "Creator")}</span>
          </p>
          <p className="text-[0.6875rem] text-text-faint">
            {(inv.items?.length ?? 0) > 0 && `${inv.items!.length} post${inv.items!.length === 1 ? "" : "s"} · `}
            {raisedByCreator ? "Raised by creator" : `Generated by ${inv.raisedBy!.name ?? inv.raisedBy!.role.toLowerCase()}`}
            {inv.isGstInvoice && " · GST invoice"}
            {inv.overdueDays > 0 && <span className="font-semibold text-rose"> · Overdue {inv.overdueDays}d</span>}
            {overQuota > 0 && inv.status !== "REJECTED" && inv.status !== "PAID" && (
              <span className="font-semibold text-rose" data-testid="campaign-invoice-over-quota">
                {" "}
                · {overQuota} post{overQuota === 1 ? "" : "s"} over the booking — reject to re-raise
              </span>
            )}
          </p>
          <div className="mt-1">
            <InvoiceAttachmentControl token={token} invoice={inv} compact />
          </div>
        </div>
        <div className="flex items-center gap-1.5">
          <StatusPill status={inv.status} />
          <StatusPill status={inv.paymentStatus} />
        </div>
        <span className="min-w-[88px] text-right text-[0.9375rem] font-semibold tabular-nums">{money(inv.amount)}</span>
        <div className="flex items-center gap-1.5">
          {isAdmin && inv.status === "RAISED" && overQuota === 0 && (
            <Button size="sm" className="h-8" onClick={() => approveMutation.mutate()} disabled={approveMutation.isPending}>
              Approve
            </Button>
          )}
          {canMarkPaid && payable && (
            <Button size="sm" className="h-8" onClick={() => setPaying(true)}>
              Mark paid
            </Button>
          )}
          <button
            type="button"
            title="Download PDF"
            aria-label={`Download ${inv.invoiceNumber} PDF`}
            onClick={() => downloadMutation.mutate()}
            disabled={downloadMutation.isPending}
            className="flex h-8 w-8 items-center justify-center rounded-md text-text-faint hover:bg-surface-2 hover:text-text-muted disabled:opacity-50"
          >
            <DownloadIcon className="h-3.5 w-3.5" />
          </button>
        </div>
      </div>
      {error && <ErrorNotice message={error instanceof ApiError ? error.message : "Something went wrong."} />}

      {paying && (
        <PaySheet
          mode="new"
          token={token}
          vendor={inv.creator!}
          links={[]}
          invoices={[toPaymentInvoice(inv)]}
          onRemoveLink={() => {}}
          onRemoveInvoice={() => setPaying(false)}
          onClose={() => setPaying(false)}
          onPaid={() => {
            setPaying(false);
            refresh();
            queryClient.invalidateQueries({ queryKey: ["payments"] });
          }}
        />
      )}
    </div>
  );
}
