import { Router } from "express";
import { requireAuth } from "../../middleware/requireAuth.js";
import { requireRole } from "../../middleware/requireRole.js";
import { requireAccess } from "../../middleware/requireAccess.js";
import { validateBody, validateQuery } from "../../middleware/validate.js";
import {
  bulkInvoiceSchema,
  gstStatusSchema,
  paymentStatusSchema,
  rejectInvoiceSchema,
  listInvoicesQuerySchema,
  confirmAttachmentSchema,
} from "./schemas.js";
import * as invoicesService from "./service.js";
import { buildInvoicePdf } from "../../lib/invoicePdf.js";

const router = Router();
router.use(requireAuth);

router.get("/", validateQuery(listInvoicesQuerySchema), async (req, res, next) => {
  try {
    res.json(await invoicesService.listInvoices(req.user, req.query));
  } catch (err) {
    next(err);
  }
});

// Creators raise their own invoices (user request, 13 Sep — "invoice will
// be generated by creator's only"); Admin/Finance approve and pay them.
router.post("/bulk", requireRole("CREATOR"), validateBody(bulkInvoiceSchema), async (req, res, next) => {
  try {
    res.status(201).json(await invoicesService.bulkCreateInvoice(req.user, req.body));
  } catch (err) {
    next(err);
  }
});

// Admin-only sign-off (RAISED → APPROVED) — Finance pays, Admin vets; see
// approveInvoice for why Finance's mark-paid doesn't strictly wait on it.
router.post("/:id/approve", requireAccess("finance.manage"), async (req, res, next) => {
  try {
    res.json(await invoicesService.approveInvoice(req.params.id, req.user));
  } catch (err) {
    next(err);
  }
});

router.post("/:id/mark-paid", requireAccess("finance.manage", "FINANCE"), async (req, res, next) => {
  try {
    res.json(await invoicesService.markPaid(req.params.id, req.user));
  } catch (err) {
    next(err);
  }
});

router.put("/:id/gst-status", requireAccess("finance.manage", "FINANCE"), validateBody(gstStatusSchema), async (req, res, next) => {
  try {
    res.json(await invoicesService.updateGstStatus(req.params.id, req.body.gstStatus));
  } catch (err) {
    next(err);
  }
});

router.put("/:id/payment-status", requireAccess("finance.manage", "FINANCE"), validateBody(paymentStatusSchema), async (req, res, next) => {
  try {
    res.json(await invoicesService.updatePaymentStatus(req.params.id, req.body.paymentStatus));
  } catch (err) {
    next(err);
  }
});

router.post("/:id/reject", requireAccess("finance.manage", "FINANCE"), validateBody(rejectInvoiceSchema), async (req, res, next) => {
  try {
    res.json(await invoicesService.rejectInvoice(req.params.id, req.user, req.body));
  } catch (err) {
    next(err);
  }
});

// Attached invoice document (12 Sep) — no requireRole: access is per
// invoice (its creator, Admin, Finance, or the Plan Maker whose campaign
// it's on), decided in the service via the same rule as GET detail.
router.post("/:id/attachment/upload-url", async (req, res, next) => {
  try {
    res.json(await invoicesService.requestAttachmentUpload(req.params.id, req.user));
  } catch (err) {
    next(err);
  }
});

router.post("/:id/attachment", validateBody(confirmAttachmentSchema), async (req, res, next) => {
  try {
    res.status(201).json(await invoicesService.confirmAttachment(req.params.id, req.user, req.body));
  } catch (err) {
    next(err);
  }
});

router.delete("/:id/attachment", async (req, res, next) => {
  try {
    await invoicesService.removeAttachment(req.params.id, req.user);
    res.status(204).end();
  } catch (err) {
    next(err);
  }
});

// Plain-text list of post URLs — creator.wldd.in's "Download Links" action.
router.get("/:id/links.txt", async (req, res, next) => {
  try {
    const urls = await invoicesService.getInvoiceLinksList(req.params.id, req.user);
    res.setHeader("Content-Type", "text/plain");
    res.setHeader("Content-Disposition", `attachment; filename="invoice-${req.params.id}-links.txt"`);
    res.send(urls.join("\n"));
  } catch (err) {
    next(err);
  }
});

// Downloadable PDF — same visibility rule as GET /invoices (own invoices,
// or any invoice for ADMIN/FINANCE), enforced in getInvoiceDetail.
router.get("/:id/pdf", async (req, res, next) => {
  try {
    const invoice = await invoicesService.getInvoiceDetail(req.params.id, req.user);
    const pdf = await buildInvoicePdf(invoice);
    res.setHeader("Content-Type", "application/pdf");
    res.setHeader("Content-Disposition", `attachment; filename="${invoice.invoiceNumber}.pdf"`);
    res.setHeader("Content-Length", pdf.length);
    res.send(pdf);
  } catch (err) {
    next(err);
  }
});

export default router;
