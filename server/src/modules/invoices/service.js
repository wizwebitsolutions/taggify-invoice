/**
 * Reject an invoice with a reason (creator.wldd.in shows this happening
 * regularly — "duplicate links", "cost difference", "date mismatch").
 * The links that were rolled into it go back to whatever status they
 * actually held right before this invoice picked them up — not always
 * INSIGHTS_APPROVED, since invoicing requires neither insights nor a
 * screenshot (see INVOICEABLE_STATUSES above): a link invoiced straight
 * from SUBMITTED must return to SUBMITTED, not silently gain an approval
 * it never had. With no prior event on record at all, SUBMITTED is the
 * neutral fallback (every link starts there).
 */
export async function rejectInvoice(invoiceId, admin, { remarks }) {
  const invoice = await prisma.invoice.findUnique({ where: { id: invoiceId }, include: { items: true } });
  if (!invoice) throw new ApiError(404, "INVOICE_NOT_FOUND", "Invoice not found");
  if (invoice.status === "PAID") {
    throw new ApiError(409, "ALREADY_PAID", "A paid invoice can't be rejected");
  }
  // Finance is mid-payout on this invoice (a DRAFT payout holds its links): rejecting now
  // would free the links while the payout still pays the invoice's amount.
  const onPayout = await prisma.payoutItem.count({ where: { linkId: { in: invoice.items.map((i) => i.linkId) } } });
  if (onPayout > 0) {
    throw new ApiError(409, "ON_PAYOUT", "This invoice is on a payout awaiting its receipt — cancel that payout in Payments before rejecting it");
  }
  if (invoice.status === "REJECTED") {
    throw new ApiError(409, "ALREADY_REJECTED", "Invoice is already rejected");
  }

  const linkIds = invoice.items.map((i) => i.linkId);

  const updated = await prisma.$transaction(async (tx) => {
    const result = await tx.invoice.update({
      where: { id: invoiceId },
      data: { status: "REJECTED", paymentStatus: "CANCELLED", remarks },
    });
    // Release the links: InvoiceItem.linkId is unique, so leaving the
    // rows here would make every link on a rejected invoice permanently
    // un-invoiceable (the very thing the reject flow promises — "eligible
    // to be re-invoiced once the issue is fixed"). The rejected invoice
    // keeps its amount/subtotal/remarks as the record of what was billed.
    await tx.invoiceItem.deleteMany({ where: { invoiceId } });
    for (const linkId of linkIds) {
      const priorEvent = await tx.linkStatusEvent.findFirst({
        where: { linkId, status: { not: "INVOICED" } },
        orderBy: { createdAt: "desc" },
      });
      const priorStatus = priorEvent?.status ?? "SUBMITTED";
      await tx.link.update({ where: { id: linkId }, data: { status: priorStatus } });
      await tx.linkStatusEvent.create({
        data: { linkId, status: priorStatus, actedById: admin.id, note: `Invoice rejected: ${remarks}` },
      });
    }
    return result;
  });

  await notifyQuietly(invoice.creatorId, "invoice_rejected", { invoiceId, remarks });
  return updated;
}

