/**
 * Fetches one invoice with everything the PDF needs (creator, and each
 * item's link → asset/campaign). Same visibility rule as listInvoices:
 * ADMIN/FINANCE see any invoice, everyone else only their own.
 */
export async function getInvoiceDetail(invoiceId, user) {
  const invoice = await prisma.invoice.findUnique({
    where: { id: invoiceId },
    include: {
      creator: true,
      campaign: { select: { id: true, title: true, brandName: true } },
      raisedBy: { select: { id: true, name: true, role: true } },
      items: { include: { link: { include: { asset: true, campaign: { select: { id: true, brandName: true, title: true, deadline: true, sheetLink: true, parentCampaignId: true, phaseNumber: true, postNumber: true, createdAt: true, updatedAt: true } } } } } },
    },
  });
  if (!invoice) throw new ApiError(404, "INVOICE_NOT_FOUND", "Invoice not found");
  // Fresh from the DB (23 Sep, Step 3) — same finance.view check as the list.
  const effective = await loadEffectivePermissions(user.id);
  const visible =
    effective["finance.view"] ||
    invoice.creatorId === user.id ||
    (user.role === "PLAN_MAKER" && invoice.campaignId && (await canPlanMakerAccessCampaign(user.id, invoice.campaignId)));
  if (!visible) {
    throw new ApiError(404, "INVOICE_NOT_FOUND", "Invoice not found");
  }

  const now = Date.now();
  const overdueDays =
    invoice.status !== "PAID" && invoice.dueDate && invoice.dueDate.getTime() < now
      ? Math.floor((now - invoice.dueDate.getTime()) / (24 * 60 * 60 * 1000))
      : 0;

  // Approved billing profile (PAN/GSTIN/bank details) powers the PDF's "Bill To"
  // block, if the creator has registered and been approved for one.
  const billingProfile = await getApprovedForUser(invoice.creatorId);

  return {
    ...invoice,
    overdueDays,
    billingProfile,
    attachment: attachmentFor(invoice),
    receipt: invoiceReceiptFor(invoice),
    overQuotaCount: invoice.items.filter((i) => i.link?.overQuota).length,
  };
}
