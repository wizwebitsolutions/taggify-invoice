// A submitted link is invoiceable as-is (user request, 12 Sep — "remove
// concept of mandatory screenshot before invoice generation"). The
// screenshot upload/review and the insights scrape both still exist, but
// as *optional* evidence steps: a link in any of those in-progress states
// is just as billable as a bare SUBMITTED one. The only things that block
// invoicing are an admin's explicit "this isn't valid work" verdicts —
// SCREENSHOT_REJECTED (proof was wrong) and INVALID (dead/broken post) —
// plus INVOICED itself (already billed).
export const INVOICEABLE_STATUSES = new Set([
  "SUBMITTED",
  "PENDING_SCREENSHOT_REVIEW",
  "SCREENSHOT_APPROVED",
  "INSIGHTS_PENDING",
  "INSIGHTS_APPROVED",
]);

// Flat rate, not a lookup table — matches the source request's "automatically
// add 18% gst to amount" exactly. If GST ever needs to vary (by state,
// service category, etc.) this is the one place to generalize.
const GST_RATE = 0.18;

/**
 * Bulk-generates one invoice from a set of eligible links (per
 * recommend.md #3 — replaces one-at-a-time invoicing). Eligibility: not
 * rejected/broken (see INVOICEABLE_STATUSES) and not already attached to an
 * invoice. All links must belong to the same creator (an invoice is
 * per-creator).
 *
 * `isGstInvoice` picks which of the two invoice types the raiser wants
 * (newTask.md #4): a GST invoice adds a flat 18% on top of the links'
 * subtotal, a non-GST invoice bills the subtotal as-is. `amount` (the
 * field every other part of the app already reads as "the invoice total" —
 * KPI tiles, markPaid, the PDF's Total line) is always subtotal + gstAmount,
 * so nothing downstream needed to change to understand a GST invoice.
 */
export async function bulkCreateInvoice(actor, { linkIds, dueInDays, isGstInvoice }) {
  // Only the creator raises their own invoice (user request, 13 Sep —
  // "invoice will be generated by creator's only"): the route is CREATOR-
  // only too, but a service-level check means no future route can quietly
  // reopen admin-generated invoices.
  if (actor.role !== "CREATOR") {
    throw new ApiError(403, "CREATOR_ONLY", "Only a creator can raise an invoice for their own pages");
  }
  const links = await prisma.link.findMany({
    where: { id: { in: linkIds } },
    include: LINK_INCLUDE_FOR_INVOICING,
  });

  if (links.length !== linkIds.length) {
    throw new ApiError(404, "LINK_NOT_FOUND", "One or more links do not exist");
  }
  assertLinksInvoiceable(links);
  const creatorIds = new Set(links.map((l) => l.asset.ownerId));
  if (creatorIds.size > 1) {
    throw new ApiError(400, "MIXED_CREATORS", "All links in one invoice must belong to the same creator");
  }
  const creatorId = [...creatorIds][0];
  // creatorId is derived from the links, so without this a creator who
  // knew another creator's link ids could raise (and lock as INVOICED) an
  // invoice payable to someone else.
  if (creatorId !== actor.id) {
    throw new ApiError(403, "FORBIDDEN", "You can only raise an invoice for your own pages");
  }
  // Tag the invoice with its campaign when every link is from one — lets
  // the campaign page list it alongside the ones generated there.
  const campaignIds = new Set(links.map((l) => l.campaignId).filter(Boolean));
  const campaignId = campaignIds.size === 1 ? [...campaignIds][0] : null;

  const invoice = await prisma.$transaction(async (tx) => {
    const created = await tx.invoice.create({
      data: {
        creatorId,
        campaignId,
        raisedById: actor.id,
        invoiceNumber: newInvoiceNumber(),
        ...invoiceTotals(links, isGstInvoice),
        isGstInvoice,
        status: "RAISED",
        dueDate: dueDateFrom(dueInDays),
        items: { create: links.map((l) => ({ linkId: l.id, amount: l.cost })) },
      },
      include: { items: true },
    });
    await markLinksInvoiced(tx, linkIds, actor.id);
    return created;
  });

  await notifyQuietly(creatorId, "invoice_raised", { invoiceId: invoice.id, amount: invoice.amount });
  return invoice;
}

// ── Helpers for bulkCreateInvoice ─────────────────────────────────────

/**
 * Status must be invoiceable AND the link must not already sit on an
 * invoice. The second check matters even though INVOICED status should
 * imply it: link status and InvoiceItem can drift apart (a re-run seed
 * resetting statuses, a manual fix-up), and InvoiceItem.linkId is unique
 * — so this reports it as "on invoice X" rather than letting the insert
 * blow up with a unique-constraint 500. Names the URL, not the id, since
 * that's what a person can actually find on screen.
 */
function assertLinksInvoiceable(links) {
  const ineligible = links.filter((l) => !INVOICEABLE_STATUSES.has(l.status) || l.invoiceItem);
  if (ineligible.length === 0) return;
  const describe = (l) => (l.invoiceItem ? `${l.url} (already on invoice ${l.invoiceItem.invoice?.invoiceNumber ?? l.invoiceItem.invoiceId})` : `${l.url} (${l.status.toLowerCase().replace(/_/g, " ")})`);
  throw new ApiError(400, "INELIGIBLE_LINKS", `Not eligible for invoicing: ${ineligible.map(describe).join("; ")}`);
}

const LINK_INCLUDE_FOR_INVOICING = { asset: true, invoiceItem: { include: { invoice: { select: { invoiceNumber: true, status: true } } } } };

function newInvoiceNumber() {
  return `INV-${Date.now()}-${nanoid(6).toUpperCase()}`;
}

function dueDateFrom(dueInDays) {
  return new Date(Date.now() + dueInDays * 24 * 60 * 60 * 1000);
}

/** subtotal/gstAmount/amount for a set of links. Every figure rounded to paise so float drift can't leave amount !== subtotal + gstAmount by a fraction once stored as Decimal(12,2). */
function invoiceTotals(links, isGstInvoice) {
  const paise = (n) => Math.round(n * 100) / 100;
  const subtotal = paise(links.reduce((sum, l) => sum + Number(l.cost), 0));
  const gstAmount = isGstInvoice ? paise(subtotal * GST_RATE) : 0;
  return { subtotal, gstAmount, amount: paise(subtotal + gstAmount) };
}

async function markLinksInvoiced(tx, linkIds, actedById) {
  await tx.link.updateMany({ where: { id: { in: linkIds } }, data: { status: "INVOICED" } });
  await tx.linkStatusEvent.createMany({ data: linkIds.map((linkId) => ({ linkId, status: "INVOICED", actedById })) });
}

/**
 * Notifications are a courtesy, written after the invoice transaction has
 * already committed — a failure here must not turn a successful generate
 * into a 500 (the user would retry and hit "already invoiced" with no
 * invoice visible until a refetch).
 */
async function notifyQuietly(userId, type, payload) {
  try {
    await notify(userId, type, payload);
  } catch (err) {
    console.error(`[invoices] notify(${type}) failed for ${userId}:`, err?.message ?? err);
  }
}

export async function listInvoices(user, filters) {
  const where = {};
  // Plan Maker sees the invoices of their own plans' campaigns *plus* any
  // billed to them personally, should they also own pages; every other
  // non-Admin/Finance role sees only invoices billed to them.
  if (user.role === "PLAN_MAKER") where.OR = [{ campaign: planMakerCampaignWhere(user.id) }, { creatorId: user.id }];
  else if (!["ADMIN", "FINANCE"].includes(user.role)) where.creatorId = user.id;
  if (filters.campaignId) where.campaignId = filters.campaignId;
  if (filters.status) where.status = filters.status;
  if (filters.paymentStatus) where.paymentStatus = filters.paymentStatus;
  if (filters.search) where.invoiceNumber = { contains: filters.search, mode: "insensitive" };

  const [items, total] = await prisma.$transaction([
    prisma.invoice.findMany({
      where,
      // creator wasn't included here — the invoices table had nowhere to
      // read a name from and fell back to literally printing "Creator" in
      // that column for every row (see client/app/invoices/page.tsx).
      include: {
        creator: { select: { id: true, name: true, phoneNumber: true } },
        campaign: { select: { id: true, title: true, brandName: true } },
        raisedBy: { select: { id: true, name: true, role: true } },
        items: { include: { link: true } },
      },
      orderBy: { createdAt: "desc" },
      skip: (filters.page - 1) * filters.pageSize,
      take: filters.pageSize,
    }),
    prisma.invoice.count({ where }),
  ]);

  // aging indicator (recommend.md #4) computed here rather than stored
  const now = Date.now();
  const withAging = items.map((inv) => ({
    ...inv,
    overdueDays:
      inv.status !== "PAID" && inv.dueDate && inv.dueDate.getTime() < now
        ? Math.floor((now - inv.dueDate.getTime()) / (24 * 60 * 60 * 1000))
        : 0,
    attachment: attachmentFor(inv),
  }));

  return { items: withAging, total, page: filters.page, pageSize: filters.pageSize };
}

// ── Attached invoice document (12 Sep) ─────────────────────────────────
// The creator's own invoice (their GST invoice PDF/image) stored against
// the Invoice record so Finance has it next to the system-generated one.
// Same direct-to-Cloudinary two-step as screenshots (screenshots/service.js):
// mint a signed upload, then confirm once the bytes are actually there.

/** Public shape — never the raw public_id, always a usable URL plus the original file name. */
function attachmentFor(invoice) {
  if (!invoice.attachmentPublicId) return null;
  return {
    name: invoice.attachmentName ?? "Attached invoice",
    url: publicUrlFor(invoice.attachmentPublicId),
    uploadedAt: invoice.attachmentUploadedAt,
    uploadedById: invoice.attachmentUploadedById,
  };
}

/**
 * Who may attach/replace/remove the document: the creator it's billed to,
 * Admin, Finance, or the Plan Maker whose campaign it's on. Same
 * visibility rule as getInvoiceDetail — if you can see it you can attach
 * to it — so the two can't drift apart.
 */
async function getWritableInvoice(invoiceId, user) {
  return getInvoiceDetail(invoiceId, user);
}

export async function requestAttachmentUpload(invoiceId, user) {
  const invoice = await getWritableInvoice(invoiceId, user);
  if (invoice.status === "PAID") throw new ApiError(409, "ALREADY_PAID", "A paid invoice's attachment can't be changed");
  return getUploadParams(buildInvoiceAttachmentKey(invoiceId));
}

export async function confirmAttachment(invoiceId, user, { publicId, fileName }) {
  const invoice = await getWritableInvoice(invoiceId, user);
  if (invoice.status === "PAID") throw new ApiError(409, "ALREADY_PAID", "A paid invoice's attachment can't be changed");
  if (!publicId.startsWith(`invoice-attachments/${invoiceId}/`)) {
    throw new ApiError(400, "KEY_MISMATCH", "Object key does not belong to this invoice");
  }
  if (!(await objectExists(publicId))) {
    throw new ApiError(422, "UPLOAD_NOT_FOUND", "No file found at that key — upload may not have completed");
  }
  const updated = await prisma.invoice.update({
    where: { id: invoiceId },
    data: { attachmentPublicId: publicId, attachmentName: fileName, attachmentUploadedById: user.id, attachmentUploadedAt: new Date() },
  });
  return attachmentFor(updated);
}

/** Clears the reference only — the object stays in Cloudinary (no delete credentials needed, and a mistaken removal is recoverable). */
export async function removeAttachment(invoiceId, user) {
  const invoice = await getWritableInvoice(invoiceId, user);
  if (invoice.status === "PAID") throw new ApiError(409, "ALREADY_PAID", "A paid invoice's attachment can't be changed");
  if (!invoice.attachmentPublicId) return null;
  await prisma.invoice.update({
    where: { id: invoiceId },
    data: { attachmentPublicId: null, attachmentName: null, attachmentUploadedById: null, attachmentUploadedAt: null },
  });
  return null;
}

/**
 * Payments are manual — Finance confirms outside the system, then records
 * it here. No gateway/webhook involved. Only an APPROVED invoice can be
 * paid (12 Sep): a creator-raised one needs Admin's approveInvoice first,
 * a campaign-generated one is already APPROVED — so Admin's sign-off is a
 * real gate on the money, not advisory. Rejected invoices are closed.
 */
export async function markPaid(invoiceId, financeUser) {
  const invoice = await prisma.invoice.findUnique({ where: { id: invoiceId } });
  if (!invoice) throw new ApiError(404, "INVOICE_NOT_FOUND", "Invoice not found");
  if (invoice.status === "PAID") {
    throw new ApiError(409, "ALREADY_PAID", "Invoice is already marked paid");
  }
  if (invoice.status !== "APPROVED") {
    throw new ApiError(
      409,
      "NOT_APPROVED",
      invoice.status === "RAISED" ? "This invoice needs an admin's approval before it can be marked paid" : `A ${invoice.status.toLowerCase()} invoice can't be marked paid`
    );
  }

  const updated = await prisma.invoice.update({
    where: { id: invoiceId },
    data: { status: "PAID", paymentStatus: "COMPLETED", paidAt: new Date() },
  });

  await notifyQuietly(invoice.creatorId, "invoice_paid", { invoiceId, markedById: financeUser.id });
  return updated;
}

/**
 * Admin signs off a creator-raised invoice (RAISED → APPROVED) — the step
 * that was missing before 12 Sep: APPROVED existed in the enum but nothing
 * ever set it, so Finance was marking RAISED invoices paid with no explicit
 * admin check in between. Finance's mark-paid is unchanged and still accepts a
 * RAISED invoice too, so this is a gate Finance *can* wait on, not one
 * that suddenly blocks payment of everything already in flight.
 */
export async function approveInvoice(invoiceId, admin) {
  const invoice = await prisma.invoice.findUnique({ where: { id: invoiceId } });
  if (!invoice) throw new ApiError(404, "INVOICE_NOT_FOUND", "Invoice not found");
  if (invoice.status !== "RAISED") {
    throw new ApiError(409, "INVALID_STATUS", `Only a raised invoice can be approved (this one is ${invoice.status.toLowerCase()})`);
  }

  const updated = await prisma.invoice.update({ where: { id: invoiceId }, data: { status: "APPROVED" } });
  await notifyQuietly(invoice.creatorId, "invoice_approved", { invoiceId, approvedById: admin.id });
  return updated;
}

